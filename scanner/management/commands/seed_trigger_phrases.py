class Command(BaseCommand):
    help = "Добавить фразы-триггеры из согласованного начального списка"

    def handle(self, *args, **options):
        created = 0
        skipped = 0
        for phrase in TRIGGER_PHRASES:
            if Keyword.objects.filter(phrase__iexact=phrase).exists():
                skipped += 1
                continue
            Keyword.objects.create(phrase=phrase)
            created += 1
        self.stdout.write(self.style.SUCCESS(
            f"Фразы-триггеры: создано {created}, уже существовало {skipped}"
        ))
